def set_event_publisher(publisher: Optional[Callable[[str, dict], None]]) -> None:
    """Optional verified MSFLib eventbus adapter; not enabled by default."""
    global _event_publisher
    with lock:
        _event_publisher = publisher


class Telemetry(BaseModel):
    device: str = Field(default='gridnova-esp32', min_length=1, max_length=80)
    mode: str = Field(default='SIMULATED_DEMAND_REAL_TEMPERATURE', max_length=100)
    load1: bool
    load2: bool
    auto: bool
    overload: bool
    thermal_trip: bool = False
    temperature_c: float | None = None
    demand_w: float = Field(ge=0, allow_inf_nan=False)
    connected_w: float = Field(ge=0, allow_inf_nan=False)
    limit_w: float = Field(gt=0, allow_inf_nan=False)

    @field_validator('temperature_c')
    @classmethod
    def finite_temperature(cls, value: float | None) -> float | None:
        if value is not None and not math.isfinite(value):
            raise ValueError('temperature_c must be finite')
        return value


class Command(BaseModel):
    command: str


def authorize(actual: str | None, env: str) -> None:
    expected = os.getenv(env, '')
    if not expected or not actual or not secrets.compare_digest(actual, expected):
        raise HTTPException(status_code=401, detail='Invalid credentials')


def publish_event(name: str, data: dict) -> None:
    event = {'event': name, 'time': time.time(), **data}
    with engine.begin() as conn:
        conn.execute(text('''INSERT INTO gridnova_events (ts,name,device)
                             VALUES (:ts,:name,:device)'''),
                     {'ts': event['time'], 'name': name,
                      'device': data.get('device', 'gridnova-esp32')})
    with lock:
        events.append(event)
        publisher = _event_publisher
    if publisher is not None:
        try:
            publisher(name, event)
        except Exception:
            logger.exception('Configured event publisher failed')


@router.post('/telemetry')
def telemetry(item: Telemetry, x_device_key: str | None = Header(default=None)):
    authorize(x_device_key, 'DEVICE_KEY')
    now = time.time()
    with engine.begin() as conn:
        conn.execute(text('''INSERT INTO gridnova_telemetry
            (ts,device,mode,temperature_c,demand_w,connected_w,limit_w,
             load1,load2,auto,overload,thermal_trip)
            VALUES (:ts,:device,:mode,:temperature_c,:demand_w,:connected_w,
                    :limit_w,:load1,:load2,:auto,:overload,:thermal_trip)'''),
            {'ts': now, **item.model_dump()})
    with lock:
        continuous = state['updated_at'] is not None and now - state['updated_at'] < 25
        previous = dict(state)
        state.update(item.model_dump())
        state.update(updated_at=now, online=True)
        history.append({'time': now, 'temperature_c': item.temperature_c,
                        'demand_w': item.demand_w, 'connected_w': item.connected_w})
    data = {'device': item.device, 'demand_w': item.demand_w,
            'connected_w': item.connected_w, 'limit_w': item.limit_w,
            'load1': item.load1, 'load2': item.load2}
    if continuous:
        if item.overload and not previous['overload']:
            publish_event('gridsense.overload_detected', data)
        elif previous['overload'] and not item.overload:
            publish_event('gridsense.overload_cleared', data)
        if item.thermal_trip and not previous['thermal_trip']:
            publish_event('gridsense.thermal_trip', {**data, 'temperature_c': item.temperature_c})
        elif previous['thermal_trip'] and not item.thermal_trip:
            publish_event('gridsense.thermal_trip_cleared', {**data, 'temperature_c': item.temperature_c})
        if previous['load2'] and not item.load2 and item.auto and item.overload:
            publish_event('gridsense.load_shedding_reported', data)
    return {'ok': True}


@router.get('/device-command', response_class=PlainTextResponse)
def device_command(x_device_key: str | None = Header(default=None)):
    authorize(x_device_key, 'DEVICE_KEY')
    with lock:
        return queue.popleft() if queue else 'none'


@router.get('/status')
def status(x_admin_key: str | None = Header(default=None)):
    authorize(x_admin_key, 'ADMIN_KEY')
    with lock:
        result = dict(state)
        result['online'] = bool(result['updated_at'] is not None and
                                time.time() - result['updated_at'] < 25)
        result['history'] = list(history)
        result['events'] = list(events)
        result['pending_commands'] = len(queue)
    return result


@router.post('/command')
def send_command(item: Command, x_admin_key: str | None = Header(default=None)):
    authorize(x_admin_key, 'ADMIN_KEY')
    cmd = ' '.join(item.command.strip().lower().split())
    if cmd not in {'1', '2', 'auto', 'reset', 'status', 'demo'} and not re.fullmatch(
            r'limit (?:[1-9][0-9]{0,2})', cmd):
        raise HTTPException(status_code=400,
                            detail='Allowed: 1, 2, auto, reset, status, demo, limit N (1-999)')
    with lock:
        if len(queue) >= queue.maxlen:
            raise HTTPException(status_code=429, detail='Command queue full')
        queue.append(cmd)
        pending = len(queue)
    return {'queued': cmd, 'pending': pending}


REPORT_COLUMNS = ['time_local', 'device', 'mode', 'temperature_c', 'estimated_demand_w',
                  'estimated_connected_w', 'configured_limit_w', 'load1', 'load2',
                  'auto', 'estimated_limit_exceeded', 'thermal_trip']


def report_range(period: str, anchor: str | None):
    tz = ZoneInfo('Africa/Lagos')
    try:
        day = datetime.strptime(anchor, '%Y-%m-%d').date() if anchor else datetime.now(tz).date()
    except ValueError:
        raise HTTPException(status_code=422, detail='date must be YYYY-MM-DD')
    if period == 'daily':
        start = day
        end = day + timedelta(days=1)
    elif period == 'weekly':
        start = day - timedelta(days=day.weekday())
        end = start + timedelta(days=7)
    elif period == 'monthly':
        start = day.replace(day=1)
        end = start.replace(year=start.year + 1, month=1) if start.month == 12 else start.replace(month=start.month + 1)
    else:
        start = day.replace(month=1, day=1)
        end = start.replace(year=start.year + 1)
    a = datetime.combine(start, datetime.min.time(), tzinfo=tz)
    b = datetime.combine(end, datetime.min.time(), tzinfo=tz)
    return a.timestamp(), b.timestamp(), start.isoformat(), (end - timedelta(days=1)).isoformat(), tz


def report_rows(period: str, date: str | None):
    a, b, start, end, tz = report_range(period, date)
    with engine.connect() as conn:
        records = conn.execute(text('''SELECT ts,device,mode,temperature_c,demand_w,
            connected_w,limit_w,load1,load2,auto,overload,thermal_trip
            FROM gridnova_telemetry WHERE ts >= :a AND ts < :b ORDER BY ts'''),
            {'a': a, 'b': b}).mappings().all()
    rows = [[datetime.fromtimestamp(r['ts'], tz).strftime('%Y-%m-%d %H:%M:%S'),
             r['device'], r['mode'], r['temperature_c'], r['demand_w'],
             r['connected_w'], r['limit_w'], bool(r['load1']), bool(r['load2']),
             bool(r['auto']), bool(r['overload']), bool(r['thermal_trip'])] for r in records]
    return rows, start, end


@router.get('/reports/{period}')
def download_report(period: str, format: str = Query('csv', pattern='^(csv|xlsx|pdf)$'),
                    date: str | None = Query(default=None),
                    x_admin_key: str | None = Header(default=None)):
    authorize(x_admin_key, 'ADMIN_KEY')
    if period not in {'daily', 'weekly', 'monthly', 'annual'}:
        raise HTTPException(status_code=404, detail='Unknown reporting period')
    rows, start, end = report_rows(period, date)
    filename = f'gridnova_{period}_{start}_{end}.{format}'
    note = ('ESTIMATED DEMAND AND CONNECTED LOAD ONLY. DS18B20 temperature is measured. '
            'No verified voltage, current, real power or kWh. Missing samples are not interpolated.')
    if format == 'csv':
        output = io.StringIO()
        writer = csv.writer(output)
        writer.writerow(['Gridnova AI', period, start, end])
        writer.writerow([note])
        writer.writerow(REPORT_COLUMNS)
        writer.writerows(rows)
        payload = output.getvalue().encode('utf-8-sig')
        media = 'text/csv'
    elif format == 'xlsx':
        wb = Workbook()
        ws = wb.active
        ws.title = 'Telemetry'
        ws.append(['Gridnova AI', period, start, end])
        ws.append([note])
        ws.append(REPORT_COLUMNS)
        for row in rows:
            ws.append(row)
        ws.freeze_panes = 'A4'
        ws.auto_filter.ref = f'A3:L{max(3, 3 + len(rows))}'
        ws.column_dimensions['A'].width = 23
        ws.column_dimensions['B'].width = 22
        ws.column_dimensions['C'].width = 40
        output = io.BytesIO()
        wb.save(output)
        payload = output.getvalue()
        media = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
    else:
        output = io.BytesIO()
        doc = SimpleDocTemplate(output, pagesize=A4)
        styles = getSampleStyleSheet()
        elements = [Paragraph('Gridnova AI — Telemetry Report', styles['Title']),
                    Paragraph(f'{period.title()}: {start} to {end} (Africa/Lagos)', styles['Normal']),
                    Spacer(1, 12), Paragraph(note, styles['BodyText']), Spacer(1, 12),
                    Paragraph(f'Available samples: {len(rows)}', styles['Heading2'])]
        if rows:
            temps = [r[3] for r in rows if r[3] is not None]
            summary = [['Metric', 'Value'],
                       ['Average estimated demand (W)', f'{sum(r[4] for r in rows)/len(rows):.2f}'],
                       ['Average estimated connected load (W)', f'{sum(r[5] for r in rows)/len(rows):.2f}'],
                       ['Average measured temperature (C)', f'{sum(temps)/len(temps):.2f}' if temps else 'N/A'],
                       ['Estimated limit-exceeded samples', str(sum(bool(r[10]) for r in rows))],
                       ['Thermal-trip samples', str(sum(bool(r[11]) for r in rows))]]
            t = Table(summary, colWidths=[290, 150])
            t.setStyle(TableStyle([('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#d9f5ef')),
                                   ('GRID', (0, 0), (-1, -1), 0.5, colors.grey),
                                   ('VALIGN', (0, 0), (-1, -1), 'TOP')]))
            elements.append(t)
        else:
            elements.append(Paragraph('No telemetry records available for this period.', styles['Normal']))
        elements.append(Spacer(1, 15))
        elements.append(Paragraph('Summary reflects available samples, not continuous period coverage.', styles['Italic']))
        doc.build(elements)
        payload = output.getvalue()
        media = 'application/pdf'
    return StreamingResponse(io.BytesIO(payload), media_type=media,
                             headers={'Content-Disposition': f'attachment; filename="{filename}"',
                                      'Cache-Control': 'no-store'})
